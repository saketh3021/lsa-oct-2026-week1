"""
Week 1 - DATA PROFILE
=====================
Reads the raw files listed in data/raw/manifest.json and writes
docs/data_profile.md: for each file, the grain, columns and types, nulls,
distinct values and date range - plus evidence for the five known traps.

Every number in the profile is measured by this script, not typed by hand,
so the profile can be regenerated whenever the raw data changes.

Usage (from the project root)
    python src/profile_data.py
"""
import json
from pathlib import Path

import pandas as pd

RAW = Path("data/raw")
OUT = Path("docs/data_profile.md")

# What one row means in each file (the "grain").
GRAIN = {
    "appointments_regional":
        "One ICB x month x appointment status x staff type x mode x booking-wait band",
    "national_categories":
        "One sub-ICB location x day x service setting x national category",
    "actual_duration":
        "One sub-ICB location x day x consultation-length band",
}
# Descriptive (non-count) columns, used to test whether the grain is really unique.
KEY_COLS = {
    "appointments_regional": ["icb_ons_code", "appointment_month", "appointment_status",
                              "hcp_type", "appointment_mode",
                              "time_between_book_and_appointment"],
    "national_categories": ["appointment_date", "sub_icb_location_name",
                            "service_setting", "national_category"],
    "actual_duration": ["sub_icb_location_code", "appointment_date", "actual_duration"],
}


def md_table(rows, header):
    """Build a markdown table from a list of row lists."""
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def column_table(df):
    rows = []
    for c in df.columns:
        s = df[c]
        n_distinct = s.nunique()
        if pd.api.types.is_numeric_dtype(s):
            rng = f"{s.min():,} to {s.max():,}"
        elif n_distinct <= 8:
            rng = ", ".join(f"`{v}`" for v in sorted(s.dropna().unique()))
        else:
            rng = f"e.g. `{s.iloc[0]}`"
        rows.append([f"`{c}`", str(s.dtype), int(s.isna().sum()), f"{n_distinct:,}", rng])
    return md_table(rows, ["Column", "Type", "Nulls", "Distinct", "Values / range"])


def profile_file(name, df, manifest_entry):
    keys = KEY_COLS[name]
    key_dups = int(df.duplicated(subset=keys, keep=False).sum())
    full_dups = int(df.duplicated(keep="first").sum())
    total = int(df["count_of_appointments"].sum())
    extra = []
    if name == "appointments_regional":
        per_key = df.groupby(keys).size()
        extra = [
            f"- **The grain is NOT unique.** {int((per_key > 1).sum()):,} key combinations appear in "
            f"more than one row (up to {int(per_key.max())}). The sub-ICB columns were removed, so each "
            f"row is really one sub-ICB's count, and rows must be summed to reach the stated grain "
            f"({len(per_key):,} rows after summing).",
        ]
    lines = [
        f"## {name}",
        "",
        f"- **File:** `{manifest_entry['raw_file']}`  ({manifest_entry['size_bytes']/1e6:.1f} MB)",
        f"- **Grain (one row is):** {GRAIN[name]}",
        f"- **Rows:** {len(df):,}   **Columns:** {df.shape[1]}",
        f"- **Total `count_of_appointments`:** {total:,}",
        f"- **Exact duplicate rows:** {full_dups:,}",
        f"- **Rows sharing a grain key with another row:** {key_dups:,}",
        f"- **Null cells in the whole file:** {int(df.isna().sum().sum()):,}",
        *extra,
        "",
        column_table(df),
        "",
    ]
    return lines


def main(raw=RAW, out=OUT):
    raw, out = Path(raw), Path(out)
    manifest = json.loads((raw / "manifest.json").read_text())
    entries = {f["dataset"]: f for f in manifest["files"]}
    dfs = {}

    # Raw column names are read WITHOUT stripping the BOM, to show trap 2 as it really is.
    raw_header = {n: open(e["raw_file"], encoding="utf-8").readline().strip().split(",")[0]
                  for n, e in entries.items()}

    reg = pd.read_csv(entries["appointments_regional"]["raw_file"])
    cat = pd.read_csv(entries["national_categories"]["raw_file"], encoding="utf-8-sig")
    dur = pd.read_csv(entries["actual_duration"]["raw_file"])
    dfs.update(appointments_regional=reg, national_categories=cat, actual_duration=dur)

    L = ["# Data profile",
         "",
         "NHS England, *Appointments in General Practice*. Generated by "
         "`src/profile_data.py` from the raw files in `data/raw/`.",
         "",
         "## Summary", ""]
    L.append(md_table(
        [[n, f"{len(d):,}", f"{int(d.count_of_appointments.sum()):,}", GRAIN[n]]
         for n, d in dfs.items()],
        ["Dataset", "Rows", "Total appointments", "Grain"]))
    L.append("")

    # Date ranges
    L += ["## Date ranges", ""]
    cat_dates = pd.to_datetime(cat.appointment_date, format="%d/%m/%Y")
    dur_dates = pd.to_datetime(dur.appointment_date, format="%Y-%m-%d")
    L.append(md_table([
        ["appointments_regional", reg.appointment_month.min(), reg.appointment_month.max(),
         f"{reg.appointment_month.nunique()} months"],
        ["national_categories", cat_dates.min().date(), cat_dates.max().date(),
         f"{cat.appointment_month.nunique()} months, {cat_dates.nunique()} days"],
        ["actual_duration", dur_dates.min().date(), dur_dates.max().date(),
         f"{dur_dates.dt.to_period('M').nunique()} months, {dur_dates.nunique()} days"],
    ], ["Dataset", "From", "To", "Coverage"]))
    L.append("")

    # Geography
    L += ["## Geography", "",
          f"- Regional file: **{reg.icb_ons_code.nunique()}** ICBs.",
          f"- Categories file: **{cat.icb_ons_code.nunique()}** ICBs, "
          f"**{cat.sub_icb_location_name.nunique()}** sub-ICB locations.",
          f"- Duration file: **{dur.icb_ons_code.nunique()}** ICBs, "
          f"**{dur.sub_icb_location_code.nunique()}** sub-ICB locations, "
          f"**{dur.region_ons_code.nunique()}** regions.",
          ""]

    for name, df in dfs.items():
        L += profile_file(name, df, entries[name])

    # ---------- The five traps ----------
    L += ["## The five traps, with evidence", ""]

    # 1. Excel
    e = entries["actual_duration"]
    L += ["### 1. `actual_duration_csv.xlsx` is an Excel file",
          f"The source file is a workbook (`{e['source_file']}`), not text. Spark cannot read it, "
          f"so extract converted it to `{e['raw_file']}` "
          f"({e['row_count']:,} rows). The untouched original is kept in `data/raw/original/`. "
          "Dates were written as `yyyy-mm-dd` in the conversion.", ""]

    # 2. BOM
    bom_name = raw_header["national_categories"]
    L += ["### 2. Byte-order mark in `national_categories.csv`",
          f"First header read as plain UTF-8: `{bom_name!r}`. "
          f"BOM present: **{bom_name.startswith(chr(0xfeff))}**. "
          "The other two files have clean first column names "
          f"(`{raw_header['appointments_regional']}`, `{raw_header['actual_duration']}`). "
          "Fix in transform: strip the BOM from the header (read with `utf-8-sig`, or `lstrip('\\ufeff')`).", ""]

    # 3. Day-first dates
    first_num = cat.appointment_date.str.slice(0, 2).astype(int)
    second_num = cat.appointment_date.str.slice(3, 5).astype(int)
    month_match = (cat_dates.dt.strftime("%Y-%m") == cat.appointment_month).all()
    L += ["### 3. Dates are day-first text in `national_categories.csv`",
          f"- `appointment_date` loads as type `{cat.appointment_date.dtype}` (text), e.g. `{cat.appointment_date.iloc[0]}`.",
          f"- Rows whose first number is above 12 (impossible as a month): **{int((first_num > 12).sum()):,}**. "
          f"Rows whose second number is above 12: **{int((second_num > 12).sum()):,}**. "
          "That proves the format is day/month/year.",
          f"- Parsing with `dd/MM/yyyy` gives a month equal to `appointment_month` on every row: **{month_match}**. "
          "This is the date test to reuse in Week 2.", ""]

    # 4. Duplicates
    dups = int(reg.duplicated().sum())
    total_dups = int(reg.loc[reg.duplicated(), "count_of_appointments"].sum())
    grouped = reg.groupby(KEY_COLS["appointments_regional"], as_index=False)["count_of_appointments"].sum()
    L += ["### 4. Look-alike rows in `appointments_regional.csv`",
          f"- **{dups:,}** rows are exact copies of an earlier row, carrying "
          f"**{total_dups:,}** appointments between them.",
          "- They are real appointments, not errors: the sub-ICB columns were removed from this "
          "file, so two sub-ICBs in the same ICB can produce identical rows. **Sum them, never drop them.**",
          f"- Summing by every descriptive column gives **{len(grouped):,}** rows "
          f"and the total stays **{int(grouped.count_of_appointments.sum()):,}** "
          f"(unchanged: {int(grouped.count_of_appointments.sum()) == int(reg.count_of_appointments.sum())}).",
          f"- For comparison, dropping them would lose {total_dups:,} appointments.", ""]

    # 5. Labels
    wait = sorted(reg.time_between_book_and_appointment.unique())
    dbl = [w for w in wait if "  " in w]
    L += ["### 5. Untidy labels",
          f"- Booking-wait labels with double spaces: {', '.join(f'`{w}`' for w in dbl)}.",
          f"- Staff type values: {', '.join(f'`{v}`' for v in sorted(reg.hcp_type.unique()))}. "
          "The guide says the metadata spells it `Other Practice Staff` (capital S): standardise in transform.",
          f"- Alphabetical order of wait bands: {' < '.join(f'`{w}`' for w in wait)}. "
          "`1 Day` sorts before `Same Day`, so an explicit sort order is needed.",
          f"- Duration bands: {', '.join(f'`{v}`' for v in sorted(dur.actual_duration.unique()))}.",
          f"- Service settings: {', '.join(f'`{v}`' for v in sorted(cat.service_setting.unique()))}.",
          f"- Context types: {', '.join(f'`{v}`' for v in sorted(cat.context_type.unique()))}.",
          f"- National categories: {cat.national_category.nunique()} distinct values.", ""]

    # Extra checks that Week 2 and 3 will need
    L += ["## Other findings worth carrying forward", ""]
    unk_status = reg.loc[reg.appointment_status == "Unknown", "count_of_appointments"].sum() / reg.count_of_appointments.sum()
    unk_dur = dur.loc[dur.actual_duration == "Unknown / Data Quality", "count_of_appointments"].sum()
    codes = cat.sub_icb_location_name.str.extract(r" - (\w+)\s*$")[0]
    codes_ok = bool(codes.isin(dur.sub_icb_location_code.unique()).all())
    long_codes = codes[codes.str.len() != 3]
    n_long = cat.loc[long_codes.index, "sub_icb_location_name"].nunique()
    long_example = long_codes.iloc[0]
    L += [f"- Regional file: appointments with status `Unknown` are {unk_status:.1%} of all appointments.",
          f"- Duration file: `Unknown / Data Quality` holds **{int(unk_dur):,}** appointments.",
          "- Sub-ICB code is the text after the final ` - ` in `sub_icb_location_name` "
          "(`... ICB - 00L` gives `00L`). **Codes are not always 3 characters**: "
          f"{n_long} of {cat.sub_icb_location_name.nunique()} locations have longer codes "
          f"(e.g. `{long_example}`), so never take 'the last 3 characters'. Use a pattern such as "
          "`F.regexp_extract('sub_icb_location_name', r' - (\\w+)$', 1)`.",
          f"- Check: with the pattern, every categories code appears in the duration file: **{codes_ok}**.",
          f"- Zero or negative counts: regional {int((reg.count_of_appointments<=0).sum())}, "
          f"categories {int((cat.count_of_appointments<=0).sum())}, "
          f"duration {int((dur.count_of_appointments<=0).sum())}.",
          "",
          "## Not yet checked",
          "",
          "`metadata_nhs.txt` (section 4 on data quality) was not available when this profile was "
          "generated. Read it before Week 2 and add its caveats here.", ""]

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L))
    print(f"Wrote {out} ({len(L)} lines)")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="Write docs/data_profile.md")
    ap.add_argument("--raw", type=Path, default=RAW, help="folder holding manifest.json")
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    main(a.raw, a.out)
